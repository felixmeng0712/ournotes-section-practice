const DICT = {en, zh};
const KEY = 'bdonp:lang';
function load() { try { const v = JSON.parse(localStorage.getItem(KEY)); return LANGS[v] ? v : 'en'; } catch { return 'en'; } }
export const lang = load();

export function t(key, v = {}) {
  const e = DICT[lang][key] ?? en[key];
  if (e == null) return key;
  if (typeof e === 'function') return e(v);
  if (Array.isArray(e)) return e;
  return e.replace(/\{(\w+)\}/g, (m, k) => v[k] ?? m);
}

export function setLang(l) {
  if (!LANGS[l] || l === lang) return;
  try { localStorage.setItem(KEY, JSON.stringify(l)); } catch {}
  location.reload();
}

// static text in index.html: data-i18n (text), data-i18n-html (markup from our own dictionary), data-i18n-attr="attr:key;…"
export function applyDom(root = document) {
  document.documentElement.lang = lang === 'zh' ? 'zh-Hans' : lang;
  document.title = t('doc.title');
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-attr]'))
    for (const pair of el.dataset.i18nAttr.split(';')) { const [a, k] = pair.split(':'); el.setAttribute(a, t(k)); }
  const help = root.querySelector('#help ul');
  if (help) help.innerHTML = t('help').map(s => `<li>${s}</li>`).join('');
}
